<?php

use Illuminate\Support\Facades\Schedule;

// ==========================================
// 2. محرك الاستخبارات (الشلال): يعمل الساعة 4:00 صباحاً
// ==========================================
// سيستيقظ ويقوم بمعالجة كل المستشفيات التي جلبها الرادار
Schedule::command('leads:enrich')
    ->dailyAt('04:00')
    ->timezone('Asia/Riyadh');

// ==========================================
// 3. مدير الحملات المتسلسلة (سنبنيه في المرحلة القادمة)
// ==========================================
// يرسل رسالة كل 10 دقائق أثناء الدوام (من 8 صباحاً إلى 4 عصراً)
Schedule::command('campaign:send_drip')
    ->everyTenMinutes()
    ->between('08:00', '16:00')
    ->days([0, 1, 2, 3, 4, 6]) // عدا الجمعة
    ->timezone('Asia/Riyadh');
